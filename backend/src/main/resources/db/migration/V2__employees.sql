-- Employee table introduced in Phase 3. It was absent from the inspected
-- development database at baseline time; this creates it without touching any
-- existing organization or platform-admin rows.

CREATE TABLE employees (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id   bigint          NOT NULL,
    employee_code     varchar(50)     NOT NULL,
    first_name        varchar(100)    NOT NULL,
    last_name         varchar(100)    NOT NULL,
    work_email        varchar(255)    NOT NULL,
    phone             varchar(20),
    department        varchar(100),
    designation       varchar(100),
    joining_date      date            NOT NULL,
    employment_status varchar(20)     NOT NULL,
    created_at        timestamp       NOT NULL,
    updated_at        timestamp       NOT NULL,
    deactivated_at    timestamp,
    version           bigint          NOT NULL,
    CONSTRAINT fk_employees_organization
        FOREIGN KEY (organization_id) REFERENCES organizations (id),
    CONSTRAINT uk_employees_org_code
        UNIQUE (organization_id, employee_code),
    CONSTRAINT uk_employees_org_email
        UNIQUE (organization_id, work_email)
);

CREATE INDEX idx_employees_org_status
    ON employees (organization_id, employment_status);
CREATE INDEX idx_employees_org_name
    ON employees (organization_id, last_name, first_name);

-- Phase 4 attendance domain. All tables are organization-scoped through an
-- explicit organization_id foreign key. No existing table or row is altered.

CREATE TABLE attendance_settings (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id       bigint          NOT NULL,
    time_zone_id          varchar(64)     NOT NULL,
    grace_period_minutes  integer         NOT NULL,
    calculation_policy    varchar(30)     NOT NULL,
    default_start_time    time            NOT NULL,
    default_end_time      time            NOT NULL,
    default_break_minutes integer         NOT NULL,
    default_working_days  varchar(64)     NOT NULL,
    payroll_lock_through  date,
    version               bigint          NOT NULL,
    created_at            timestamp       NOT NULL,
    updated_at            timestamp       NOT NULL,
    CONSTRAINT fk_attendance_settings_organization
        FOREIGN KEY (organization_id) REFERENCES organizations (id),
    CONSTRAINT uk_attendance_settings_organization UNIQUE (organization_id)
);

CREATE TABLE attendance_schedules (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id  bigint          NOT NULL,
    name             varchar(100)    NOT NULL,
    start_time       time            NOT NULL,
    end_time         time            NOT NULL,
    break_minutes    integer         NOT NULL,
    working_days     varchar(64)     NOT NULL,
    effective_from   date            NOT NULL,
    effective_to     date,
    active           boolean         NOT NULL,
    overnight        boolean         NOT NULL,
    version          bigint          NOT NULL,
    created_at       timestamp       NOT NULL,
    updated_at       timestamp       NOT NULL,
    CONSTRAINT fk_attendance_schedules_organization
        FOREIGN KEY (organization_id) REFERENCES organizations (id),
    CONSTRAINT uk_attendance_schedules_org_name
        UNIQUE (organization_id, name)
);

CREATE INDEX idx_attendance_schedules_org_active
    ON attendance_schedules (organization_id, active, effective_from);

CREATE TABLE employee_schedule_assignments (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id  bigint          NOT NULL,
    employee_id      bigint          NOT NULL,
    schedule_id      bigint          NOT NULL,
    effective_from   date            NOT NULL,
    effective_to     date,
    version          bigint          NOT NULL,
    created_at       timestamp       NOT NULL,
    updated_at       timestamp       NOT NULL,
    CONSTRAINT fk_schedule_assignments_organization
        FOREIGN KEY (organization_id) REFERENCES organizations (id),
    CONSTRAINT fk_schedule_assignments_employee
        FOREIGN KEY (employee_id) REFERENCES employees (id),
    CONSTRAINT fk_schedule_assignments_schedule
        FOREIGN KEY (schedule_id) REFERENCES attendance_schedules (id),
    CONSTRAINT uk_schedule_assignments_org_employee_from
        UNIQUE (organization_id, employee_id, effective_from)
);

CREATE INDEX idx_schedule_assignments_org_employee
    ON employee_schedule_assignments (organization_id, employee_id, effective_from);

CREATE TABLE attendance_events (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id  bigint                          NOT NULL,
    employee_id      bigint                          NOT NULL,
    event_type       varchar(20)                     NOT NULL,
    occurred_at      timestamp(6) with time zone     NOT NULL,
    work_date        date                            NOT NULL,
    time_zone_id     varchar(64)                     NOT NULL,
    idempotency_key  varchar(100)                    NOT NULL,
    created_at       timestamp(6) with time zone     NOT NULL,
    CONSTRAINT fk_attendance_events_organization
        FOREIGN KEY (organization_id) REFERENCES organizations (id),
    CONSTRAINT fk_attendance_events_employee
        FOREIGN KEY (employee_id) REFERENCES employees (id),
    CONSTRAINT uk_attendance_events_idempotency
        UNIQUE (organization_id, idempotency_key)
);

CREATE INDEX idx_attendance_events_org_employee_date
    ON attendance_events (organization_id, employee_id, work_date);
CREATE INDEX idx_attendance_events_org_employee_time
    ON attendance_events (organization_id, employee_id, occurred_at);

CREATE TABLE daily_attendance (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id  bigint                          NOT NULL,
    employee_id      bigint                          NOT NULL,
    work_date        date                            NOT NULL,
    status           varchar(20)                     NOT NULL,
    scheduled_start  timestamp(6) with time zone,
    scheduled_end    timestamp(6) with time zone,
    first_check_in   timestamp(6) with time zone,
    last_check_out   timestamp(6) with time zone,
    worked_minutes   integer                         NOT NULL,
    late_minutes     integer                         NOT NULL,
    break_minutes    integer                         NOT NULL,
    version          bigint                          NOT NULL,
    created_at       timestamp                       NOT NULL,
    updated_at       timestamp                       NOT NULL,
    CONSTRAINT fk_daily_attendance_organization
        FOREIGN KEY (organization_id) REFERENCES organizations (id),
    CONSTRAINT fk_daily_attendance_employee
        FOREIGN KEY (employee_id) REFERENCES employees (id),
    CONSTRAINT uk_daily_attendance_org_employee_date
        UNIQUE (organization_id, employee_id, work_date)
);

CREATE INDEX idx_daily_attendance_org_date_status
    ON daily_attendance (organization_id, work_date, status);

CREATE TABLE leave_types (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id  bigint          NOT NULL,
    name             varchar(100)    NOT NULL,
    paid             boolean         NOT NULL,
    active           boolean         NOT NULL,
    version          bigint          NOT NULL,
    created_at       timestamp       NOT NULL,
    updated_at       timestamp       NOT NULL,
    CONSTRAINT fk_leave_types_organization
        FOREIGN KEY (organization_id) REFERENCES organizations (id),
    CONSTRAINT uk_leave_types_org_name UNIQUE (organization_id, name)
);

CREATE TABLE leave_requests (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id  bigint          NOT NULL,
    employee_id      bigint          NOT NULL,
    leave_type_id    bigint          NOT NULL,
    start_date       date            NOT NULL,
    end_date         date            NOT NULL,
    reason           varchar(500)    NOT NULL,
    status           varchar(20)     NOT NULL,
    decided_by       varchar(255),
    decided_at       timestamp(6) with time zone,
    version          bigint          NOT NULL,
    created_at       timestamp       NOT NULL,
    updated_at       timestamp       NOT NULL,
    CONSTRAINT fk_leave_requests_organization
        FOREIGN KEY (organization_id) REFERENCES organizations (id),
    CONSTRAINT fk_leave_requests_employee
        FOREIGN KEY (employee_id) REFERENCES employees (id),
    CONSTRAINT fk_leave_requests_leave_type
        FOREIGN KEY (leave_type_id) REFERENCES leave_types (id)
);

CREATE INDEX idx_leave_requests_org_status_start
    ON leave_requests (organization_id, status, start_date);
CREATE INDEX idx_leave_requests_org_employee_start
    ON leave_requests (organization_id, employee_id, start_date);

CREATE TABLE holidays (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id  bigint          NOT NULL,
    name             varchar(150)    NOT NULL,
    holiday_date     date            NOT NULL,
    description      varchar(500),
    calendar_name    varchar(100),
    version          bigint          NOT NULL,
    created_at       timestamp       NOT NULL,
    updated_at       timestamp       NOT NULL,
    CONSTRAINT fk_holidays_organization
        FOREIGN KEY (organization_id) REFERENCES organizations (id),
    CONSTRAINT uk_holidays_org_date UNIQUE (organization_id, holiday_date)
);

CREATE TABLE attendance_corrections (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id    bigint                          NOT NULL,
    daily_attendance_id bigint                         NOT NULL,
    employee_id        bigint                          NOT NULL,
    reason             varchar(500)                    NOT NULL,
    previous_status    varchar(20)                     NOT NULL,
    corrected_status   varchar(20)                     NOT NULL,
    previous_check_in  timestamp(6) with time zone,
    previous_check_out timestamp(6) with time zone,
    corrected_check_in timestamp(6) with time zone,
    corrected_check_out timestamp(6) with time zone,
    expected_version   bigint                          NOT NULL,
    actor              varchar(255)                    NOT NULL,
    corrected_at       timestamp(6) with time zone     NOT NULL,
    payroll_locked     boolean                         NOT NULL,
    created_at         timestamp                       NOT NULL,
    CONSTRAINT fk_corrections_organization
        FOREIGN KEY (organization_id) REFERENCES organizations (id),
    CONSTRAINT fk_corrections_daily_attendance
        FOREIGN KEY (daily_attendance_id) REFERENCES daily_attendance (id),
    CONSTRAINT fk_corrections_employee
        FOREIGN KEY (employee_id) REFERENCES employees (id)
);

CREATE INDEX idx_corrections_org_daily
    ON attendance_corrections (organization_id, daily_attendance_id);
CREATE INDEX idx_corrections_org_time
    ON attendance_corrections (organization_id, corrected_at);

CREATE TABLE attendance_audit_records (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id  bigint                          NOT NULL,
    entity_type      varchar(50)                     NOT NULL,
    entity_id        bigint                          NOT NULL,
    action           varchar(40)                     NOT NULL,
    actor            varchar(255)                    NOT NULL,
    detail           varchar(1000)                   NOT NULL,
    occurred_at      timestamp(6) with time zone     NOT NULL,
    CONSTRAINT fk_audit_records_organization
        FOREIGN KEY (organization_id) REFERENCES organizations (id)
);

CREATE INDEX idx_audit_records_org_time
    ON attendance_audit_records (organization_id, occurred_at);
CREATE INDEX idx_audit_records_org_entity
    ON attendance_audit_records (organization_id, entity_type, entity_id);
